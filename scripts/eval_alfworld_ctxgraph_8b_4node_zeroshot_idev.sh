#!/bin/bash
# Fixed-sample zero-shot ContextGraph evaluation on official ALFWorld @real.
set -euo pipefail

PROJECT_ROOT=/work/09281/chc_1996/vista/context-graph
source /work/09281/chc_1996/vista/miniconda3/etc/profile.d/conda.sh
conda activate cxtgraph
cd "$PROJECT_ROOT"

if [ -z "${SLURM_JOB_NODELIST:-}" ]; then
  echo "ERROR: run this inside a four-node Vista idev allocation"
  exit 1
fi

ALFWORLD_EVAL_SAMPLES=${ALFWORLD_EVAL_SAMPLES:-32}
ALFWORLD_DATA_SEED=${ALFWORLD_DATA_SEED:-42}
ALFWORLD_EXPERIMENT_PREFIX=${ALFWORLD_EXPERIMENT_PREFIX:-contextgraph}
export ALFWORLD_DATA=${ALFWORLD_DATA:-$HOME/.cache/alfworld}

if ! [[ "$ALFWORLD_EVAL_SAMPLES" =~ ^[1-9][0-9]*$ ]]; then
  echo "ERROR: ALFWORLD_EVAL_SAMPLES must be a positive integer"
  exit 1
fi

python scripts/make_alfworld_data.py \
  --mode real \
  --n_train 16 \
  --n_val "$ALFWORLD_EVAL_SAMPLES" \
  --seed "$ALFWORLD_DATA_SEED" \
  --alfworld_data "$ALFWORLD_DATA"

EVAL_TS=$(date +%Y%m%d_%H%M%S)
export ALFWORLD_EXPERIMENT_NAME="${ALFWORLD_EXPERIMENT_PREFIX}_alfworld_real_8b_4n_zeroshot_n${ALFWORLD_EVAL_SAMPLES}_seed${ALFWORLD_DATA_SEED}_${EVAL_TS}"
mkdir -p logs
EVAL_LOG="logs/${ALFWORLD_EXPERIMENT_NAME}.log"
EVAL_SUMMARY="logs/${ALFWORLD_EXPERIMENT_NAME}.summary.json"

export WANDB_MODE=disabled
export ALFWORLD_DISABLE_WANDB=1
export MODEL_PATH=${MODEL_PATH:-Qwen/Qwen3-8B}
export ALFWORLD_MODE=real
export ALFWORLD_METHOD_LABEL=${ALFWORLD_METHOD_LABEL:-"ContextGraph zero-shot"}
export ALFWORLD_AGENT_LOOP=context_graph_isolated_agent
export ALFWORLD_WORKFLOW=alfworld_graph
export ALFWORLD_PROCESS_REWARD='[flat,scope,graph]'
export ALFWORLD_VAL_ONLY=True
export ALFWORLD_VAL_BEFORE_TRAIN=True
export ALFWORLD_VAL_MAX_SAMPLES="$ALFWORLD_EVAL_SAMPLES"
export ALFWORLD_TRAIN_MAX_SAMPLES=16
export ALFWORLD_TOTAL_STEPS=1
export ALFWORLD_TRAIN_BATCH_SIZE=4
export ALFWORLD_PPO_MINI_BATCH_SIZE=4
export ALFWORLD_ROLLOUT_N=1
export ALFWORLD_PROMPT_LENGTH=${ALFWORLD_PROMPT_LENGTH:-4096}
export ALFWORLD_RESPONSE_LENGTH=${ALFWORLD_RESPONSE_LENGTH:-12288}
export ALFWORLD_MAX_TOKEN_LEN_PER_GPU=${ALFWORLD_MAX_TOKEN_LEN_PER_GPU:-16384}
export ALFWORLD_MAX_TURN=${ALFWORLD_MAX_TURN:-60}
export ALFWORLD_VAL_MAX_TURN=${ALFWORLD_VAL_MAX_TURN:-$ALFWORLD_MAX_TURN}
export ALFWORLD_TURN_MAX_NEW_TOKENS=${ALFWORLD_TURN_MAX_NEW_TOKENS:-128}
export ALFWORLD_BRANCH_LEN=${ALFWORLD_BRANCH_LEN:-2048}
export ALFWORLD_MAX_SESSION=${ALFWORLD_MAX_SESSION:-3}
export ALFWORLD_VAL_MAX_SESSION=${ALFWORLD_VAL_MAX_SESSION:-$ALFWORLD_MAX_SESSION}
export ALFWORLD_STRUCTURED_GRAPH_CONTROLLER=${ALFWORLD_STRUCTURED_GRAPH_CONTROLLER:-True}
export ALFWORLD_CONTROLLER_OWNED_TOOL_FORMATTING=${ALFWORLD_CONTROLLER_OWNED_TOOL_FORMATTING:-$ALFWORLD_STRUCTURED_GRAPH_CONTROLLER}
export ALFWORLD_CONTROLLER_ACTION_POLICY=${ALFWORLD_CONTROLLER_ACTION_POLICY:-structural}
export ALFWORLD_STRUCTURED_MEMORY_ENABLED=${ALFWORLD_STRUCTURED_MEMORY_ENABLED:-${STRUCTURED_MEMORY_ENABLED:-0}}
export ALFWORLD_STRUCTURED_MEMORY_REQUIRED=${ALFWORLD_STRUCTURED_MEMORY_REQUIRED:-${STRUCTURED_MEMORY_REQUIRED:-$ALFWORLD_STRUCTURED_MEMORY_ENABLED}}
if [ -z "${ALFWORLD_SESSION_TIMEOUT:-}" ]; then
  if [ "$ALFWORLD_STRUCTURED_MEMORY_ENABLED" = "1" ]; then
    export ALFWORLD_SESSION_TIMEOUT=1800
  else
    export ALFWORLD_SESSION_TIMEOUT=600
  fi
fi
export ALFWORLD_STRUCTURED_MEMORY_TOOLS=${ALFWORLD_STRUCTURED_MEMORY_TOOLS:-action,branch_return}
export ALFWORLD_STRUCTURED_MEMORY_GAP_INTERVAL=${ALFWORLD_STRUCTURED_MEMORY_GAP_INTERVAL:-${STRUCTURED_MEMORY_GAP_INTERVAL:-8}}
export ALFWORLD_STRUCTURED_MEMORY_CONTEXT_BUDGET=${ALFWORLD_STRUCTURED_MEMORY_CONTEXT_BUDGET:-${STRUCTURED_MEMORY_CONTEXT_BUDGET:-1024}}
export ALFWORLD_STRUCTURED_MEMORY_MAX_CONTEXT_FACTS=${ALFWORLD_STRUCTURED_MEMORY_MAX_CONTEXT_FACTS:-${STRUCTURED_MEMORY_MAX_CONTEXT_FACTS:-12}}
export ALFWORLD_STRUCTURED_MEMORY_MAX_FACTS_PER_OBSERVATION=${ALFWORLD_STRUCTURED_MEMORY_MAX_FACTS_PER_OBSERVATION:-${STRUCTURED_MEMORY_MAX_FACTS_PER_OBSERVATION:-8}}
export ALFWORLD_STRUCTURED_MEMORY_MAX_FACTS=${ALFWORLD_STRUCTURED_MEMORY_MAX_FACTS:-${STRUCTURED_MEMORY_MAX_FACTS:-128}}
export ALFWORLD_STRUCTURED_MEMORY_EXTRACT_MAX_TOKENS=${ALFWORLD_STRUCTURED_MEMORY_EXTRACT_MAX_TOKENS:-${STRUCTURED_MEMORY_EXTRACT_MAX_TOKENS:-768}}
export ALFWORLD_STRUCTURED_MEMORY_GAP_MAX_TOKENS=${ALFWORLD_STRUCTURED_MEMORY_GAP_MAX_TOKENS:-${STRUCTURED_MEMORY_GAP_MAX_TOKENS:-512}}
export ALFWORLD_STRUCTURED_MEMORY_PLAN_MAX_TOKENS=${ALFWORLD_STRUCTURED_MEMORY_PLAN_MAX_TOKENS:-${STRUCTURED_MEMORY_PLAN_MAX_TOKENS:-512}}
export ALFWORLD_STRUCTURED_MEMORY_RELATION_CANDIDATES=${ALFWORLD_STRUCTURED_MEMORY_RELATION_CANDIDATES:-${STRUCTURED_MEMORY_RELATION_CANDIDATES:-128}}
export ALFWORLD_STRUCTURED_MEMORY_CONTROLLER_RETRIES=${ALFWORLD_STRUCTURED_MEMORY_CONTROLLER_RETRIES:-${STRUCTURED_MEMORY_CONTROLLER_RETRIES:-2}}
export ALFWORLD_STRUCTURED_MEMORY_GAP_JITTER=${ALFWORLD_STRUCTURED_MEMORY_GAP_JITTER:-${STRUCTURED_MEMORY_GAP_JITTER:-1}}
# ALFWorld must terminate on environment success/failure, not QA answer-readiness.
export ALFWORLD_STRUCTURED_MEMORY_STOP_ON_READY=${ALFWORLD_STRUCTURED_MEMORY_STOP_ON_READY:-0}
export ALFWORLD_STRUCTURED_MEMORY_STEP_LIMIT=${ALFWORLD_STRUCTURED_MEMORY_STEP_LIMIT:-${STRUCTURED_MEMORY_STEP_LIMIT:-40}}
export ALFWORLD_CONSOLIDATION_INTERVAL=${ALFWORLD_CONSOLIDATION_INTERVAL:-5}
export ALFWORLD_AUTO_PRUNE_MAX_ACTIVE=${ALFWORLD_AUTO_PRUNE_MAX_ACTIVE:-12}
export ALFWORLD_FINAL_ANSWER_RESERVE=${ALFWORLD_FINAL_ANSWER_RESERVE:-0}
export ALFWORLD_FINAL_ANSWER_SAFETY_MARGIN=${ALFWORLD_FINAL_ANSWER_SAFETY_MARGIN:-64}
export ALFWORLD_TRAINER_RESUME_MODE=disable

echo "=============================================================="
echo "  Zero-shot ALFWorld evaluation: ${ALFWORLD_EVAL_SAMPLES} fixed episodes"
echo "  Model: ${MODEL_PATH}; seed: ${ALFWORLD_DATA_SEED}"
echo "  Controller: structured=${ALFWORLD_STRUCTURED_GRAPH_CONTROLLER}; formatting=${ALFWORLD_CONTROLLER_OWNED_TOOL_FORMATTING}; policy=${ALFWORLD_CONTROLLER_ACTION_POLICY}"
echo "  StructMem: enabled=${ALFWORLD_STRUCTURED_MEMORY_ENABLED}; tools=${ALFWORLD_STRUCTURED_MEMORY_TOOLS}; step_limit=${ALFWORLD_STRUCTURED_MEMORY_STEP_LIMIT}; stop_on_ready=${ALFWORLD_STRUCTURED_MEMORY_STOP_ON_READY}"
echo "  Session timeout: ${ALFWORLD_SESSION_TIMEOUT}s"
echo "  Raw log: ${EVAL_LOG}"
echo "=============================================================="

set +e
bash scripts/train_alfworld_ctxgraph_8b_4node_30step.sh 2>&1 | tee "$EVAL_LOG"
RC=${PIPESTATUS[0]}
set -e

if [ "$RC" -ne 0 ]; then
  echo "ERROR: ALFWorld evaluation failed with exit code $RC; log: $EVAL_LOG"
  exit "$RC"
fi

python scripts/summarize_alfworld_eval.py "$EVAL_LOG" --samples "$ALFWORLD_EVAL_SAMPLES" --output "$EVAL_SUMMARY"
echo "Evaluation summary: $EVAL_SUMMARY"
